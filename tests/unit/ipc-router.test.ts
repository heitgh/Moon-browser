import { pathToFileURL } from "node:url";
import { resolve, join } from "node:path";
import { expect, it, vi } from "vitest";
const electron = vi.hoisted(() => ({ handle: vi.fn(), removeHandler: vi.fn() }));
vi.mock("electron", () => ({ ipcMain: electron, app: { getAppPath: () => "/moon" } }));
import { IpcRouter } from "../../apps/desktop/electron/ipc/ipc-router.js";
import type { WindowManager } from "../../apps/desktop/electron/main/window-manager.js";
it("guards registered handlers before dispatching any command", async () => {
  const mainFrame = { url: pathToFileURL(join(resolve("/moon"), "index.html")).href, detached: false };
  const sender = { isDestroyed: () => false, mainFrame, getURL: () => mainFrame.url };
  const window = { isDestroyed: () => false, webContents: sender };
  const windows = { idForWebContents: () => "shell", get: () => window } as unknown as WindowManager;
  const command = vi.fn(() => "ok"); const router = new IpcRouter(windows);
  router.register("privileged:test", command);
  const invoke = electron.handle.mock.lastCall![1]; const event = { sender, senderFrame: mainFrame };
  await expect(invoke(event, { safe: true })).resolves.toBe("ok"); command.mockClear();
  for (const frame of [null, { ...mainFrame }, { url: "https://evil.test" }]) await expect(invoke({ ...event, senderFrame: frame }, {})).rejects.toThrow();
  await expect(invoke(event, {}, {})).rejects.toThrow();
  await expect(invoke(event, { size: Infinity })).rejects.toThrow();
  expect(command).not.toHaveBeenCalled(); router.dispose(); expect(electron.removeHandler).toHaveBeenCalledWith("privileged:test");
});

it("drains an in-flight IPC operation even after handlers are disposed", async () => {
  const mainFrame = { url: pathToFileURL(join(resolve("/moon"), "index.html")).href, detached: false };
  const sender = { isDestroyed: () => false, mainFrame, getURL: () => mainFrame.url };
  const windows = { idForWebContents: () => "shell", get: () => ({ isDestroyed: () => false, webContents: sender }) } as unknown as WindowManager;
  const router = new IpcRouter(windows);
  let release!: () => void;
  router.register("profile:slow-write", async () => new Promise<void>(resolve => { release = resolve; }));
  const invoke = electron.handle.mock.lastCall![1];
  const pending = invoke({ sender, senderFrame: mainFrame }, { safe: true });
  for (let i = 0; i < 100 && !release; i++) await Promise.resolve();
  expect(release).toBeTypeOf("function");
  router.dispose();
  let finished = false;
  const draining = router.drain().then(() => { finished = true; });
  await Promise.resolve();
  expect(finished).toBe(false);
  release();
  await pending; await draining;
  expect(finished).toBe(true);
  await expect(invoke({ sender, senderFrame: mainFrame }, { safe: true })).rejects.toThrow(/shutting down/i);
});

it("refuses a locked profile before dispatch and withholds results when it locks during a command", async () => {
  const mainFrame = { url: pathToFileURL(join(resolve("/moon"), "index.html")).href, detached: false };
  const sender = { isDestroyed: () => false, mainFrame, getURL: () => mainFrame.url };
  const windows = { idForWebContents: () => "shell", get: () => ({isDestroyed: () => false, webContents: sender}) } as unknown as WindowManager;
  let locked = true;
  let release!: (value: string) => void;
  const handler = vi.fn(() => new Promise<string>(resolve => { release = resolve; }));
  const router = new IpcRouter(windows, () => { if (locked) throw new Error("locked"); });
  router.register("profile:read", handler);
  const invoke = electron.handle.mock.lastCall![1];
  const event = {sender, senderFrame: mainFrame};
  await expect(invoke(event, {})).rejects.toThrow("locked");
  expect(handler).not.toHaveBeenCalled();
  locked = false;
  const pending = invoke(event, {});
  for (let i = 0; i < 100 && !release; i++) await Promise.resolve();
  locked = true; release("sensitive data");
  await expect(pending).rejects.toThrow("locked");
  router.dispose();
});
